import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, relative, resolve, sep } from 'node:path';

export const IMMUTABLE_CACHE_CONTROL = 'public, max-age=31536000, immutable';
export const REVALIDATED_CACHE_CONTROL = 'public, max-age=0, must-revalidate';
export const RELEASE_MANIFEST_PATH = '.well-known/pinega-release.json';
export const DEPLOYMENT_MANIFEST_PATH = '.well-known/pinega-deployment.json';
export const RELEASE_SCHEMA_VERSION = 1;

const releaseInventoryExclusions = new Set([
  RELEASE_MANIFEST_PATH,
  DEPLOYMENT_MANIFEST_PATH,
]);
const nonPublicControls = new Set(['_headers']);
const immutableAssetPattern = /-(?:[A-Z0-9]{8}|[a-f0-9]{16})\.[A-Za-z0-9.]+$/u;
const mediaTypes = new Map([
  ['.css', 'text/css'],
  ['.html', 'text/html'],
  ['.js', 'text/javascript'],
  ['.json', 'application/json'],
  ['.map', 'application/json'],
  ['.svg', 'image/svg+xml'],
  ['.txt', 'text/plain'],
  ['.xml', 'application/xml'],
  ['.woff2', 'font/woff2'],
]);

export async function writeFingerprintedFile(sourcePath, outputDirectory, { urlPrefix = '/assets' } = {}) {
  const content = await readFile(sourcePath);
  const extension = extname(sourcePath);
  const stem = basename(sourcePath, extension);
  const fingerprint = sha256(content).slice(0, 16);
  const fileName = `${stem}-${fingerprint}${extension}`;
  const outputPath = resolve(outputDirectory, fileName);
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, content);
  return Object.freeze({
    outputPath,
    fileName,
    url: `${urlPrefix}/${fileName}`,
    bytes: content.byteLength,
    sha256: sha256(content),
  });
}

export async function writeFingerprintedJson(outputDirectory, stem, value) {
  if (!/^[a-z][a-z0-9-]*$/u.test(stem)) throw new TypeError(`Invalid fingerprinted JSON stem: ${JSON.stringify(stem)}`);
  const content = `${JSON.stringify(value, null, 2)}\n`;
  const fingerprint = sha256(content).slice(0, 16);
  const fileName = `${stem}-${fingerprint}.json`;
  const outputPath = resolve(outputDirectory, fileName);
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(outputPath, content, 'utf8');
  return Object.freeze({ outputPath, fileName, url: `/assets/${fileName}`, content });
}

export async function writeReleaseHeaders(root, routes) {
  const content = renderReleaseHeaders(routes);
  await writeFile(resolve(root, '_headers'), content, 'utf8');
  return content;
}

export function renderReleaseHeaders(routes) {
  if (!Array.isArray(routes) || routes.length === 0) throw new TypeError('Release headers require at least one HTML route.');
  const normalizedRoutes = [...new Set(routes.map(normalizeRoutePattern))].toSorted(compareText);
  const revalidatedPatterns = [
    ...normalizedRoutes,
    '/.well-known/*',
    '/content/*',
    '/diagrams/*',
    '/robots.txt',
    '/site-manifest.json',
    '/sitemap.xml',
  ];
  const blocks = [
    '# Generated by scripts/build.mjs. All matching asset URLs are content fingerprinted.',
    '/assets/*\n  Cache-Control: ' + IMMUTABLE_CACHE_CONTROL,
    ...revalidatedPatterns.map(pattern => `${pattern}\n  Cache-Control: ${REVALIDATED_CACHE_CONTROL}`),
  ];
  if (revalidatedPatterns.includes('/assets/*')) throw new TypeError('Immutable and revalidated header patterns must not overlap exactly.');
  if (blocks.length - 1 > 100) throw new TypeError(`Cloudflare Pages permits at most 100 header rules; generated ${blocks.length - 1}.`);
  for (const line of blocks.join('\n\n').split('\n')) {
    if (line.length > 2_000) throw new TypeError('Cloudflare Pages header line exceeds 2,000 characters.');
  }
  return `${blocks.join('\n\n')}\n`;
}

export async function writeReleaseManifest(root, buildId) {
  const manifest = await createReleaseManifest(root, buildId);
  const output = resolve(root, RELEASE_MANIFEST_PATH);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  return manifest;
}

export async function createReleaseManifest(root, buildId) {
  if (!/^sha256-[a-f0-9]{64}$/u.test(buildId)) throw new TypeError(`Invalid release build ID: ${JSON.stringify(buildId)}`);
  const paths = (await walk(root))
    .map(path => normalizePath(relative(root, path)))
    .filter(path => !releaseInventoryExclusions.has(path))
    .toSorted(compareText);
  const files = [];
  const controls = [];
  for (const path of paths) {
    const content = await readFile(resolve(root, path));
    const entry = {
      path,
      bytes: content.byteLength,
      sha256: sha256(content),
    };
    if (nonPublicControls.has(path)) {
      controls.push(Object.freeze({ ...entry, kind: 'deployment-control' }));
      continue;
    }
    const immutable = path.startsWith('assets/');
    if (immutable && !isFingerprintedAssetPath(path)) {
      throw new TypeError(`Immutable asset is not content fingerprinted: ${path}`);
    }
    const publicMapping = publicMappingForPath(path);
    files.push(Object.freeze({
      ...entry,
      url: publicMapping.url,
      status: publicMapping.status,
      cache: immutable ? 'immutable' : 'revalidate',
      cacheControl: immutable ? IMMUTABLE_CACHE_CONTROL : REVALIDATED_CACHE_CONTROL,
      mediaType: mediaTypeForPath(path),
    }));
  }
  if (controls.length !== 1 || controls[0]?.path !== '_headers') {
    throw new TypeError('Release artifact must contain exactly one generated _headers deployment control.');
  }
  const inventorySha256 = sha256(JSON.stringify(files));
  return Object.freeze({
    schemaVersion: RELEASE_SCHEMA_VERSION,
    kind: 'pinega-web-exact-artifact',
    buildId,
    digestAlgorithm: 'sha256',
    cachePolicy: Object.freeze({
      immutableAssets: IMMUTABLE_CACHE_CONTROL,
      revalidatedDocuments: REVALIDATED_CACHE_CONTROL,
      serviceWorker: false,
    }),
    inventory: Object.freeze({
      sha256: inventorySha256,
      fileCount: files.length,
      totalBytes: files.reduce((total, file) => total + file.bytes, 0),
      excludedSelf: RELEASE_MANIFEST_PATH,
      excludedDeploymentProvenance: DEPLOYMENT_MANIFEST_PATH,
    }),
    controls: Object.freeze(controls),
    files: Object.freeze(files),
  });
}

export async function verifyReleaseManifest(root, manifest) {
  validateReleaseManifestShape(manifest);
  const actual = await createReleaseManifest(root, manifest.buildId);
  if (JSON.stringify(actual) !== JSON.stringify(manifest)) {
    throw new TypeError('Release manifest does not match the exact artifact bytes.');
  }
  return actual;
}

export function isFingerprintedAssetPath(path) {
  const normalized = normalizePath(path);
  return normalized.startsWith('assets/') && immutableAssetPattern.test(basename(normalized));
}

export function publicMappingForPath(path) {
  const normalized = normalizePath(path);
  if (!normalized || normalized.startsWith('/') || normalized === '..' || normalized.startsWith('../') || normalized.includes('/../') || normalized.endsWith('/..')) {
    throw new TypeError(`Invalid release artifact path: ${JSON.stringify(path)}`);
  }
  if (normalized === '404.html') {
    return Object.freeze({ url: '/__pinega-release-verification-missing__', status: 404 });
  }
  if (normalized === 'ru/404.html') {
    return Object.freeze({ url: '/ru/__pinega-release-verification-missing__', status: 404 });
  }
  if (normalized === 'index.html') return Object.freeze({ url: '/', status: 200 });
  if (normalized.endsWith('/index.html')) {
    return Object.freeze({ url: `/${normalized.slice(0, -'index.html'.length)}`, status: 200 });
  }
  return Object.freeze({ url: `/${normalized}`, status: 200 });
}

export function mediaTypeForPath(path) {
  return mediaTypes.get(extname(path).toLowerCase()) ?? null;
}

function validateReleaseManifestShape(manifest) {
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) throw new TypeError('Release manifest must be an object.');
  if (manifest.schemaVersion !== RELEASE_SCHEMA_VERSION) throw new TypeError(`Unsupported release manifest schema: ${JSON.stringify(manifest.schemaVersion)}`);
  if (manifest.kind !== 'pinega-web-exact-artifact') throw new TypeError(`Unsupported release manifest kind: ${JSON.stringify(manifest.kind)}`);
  if (!Array.isArray(manifest.files) || !Array.isArray(manifest.controls)) throw new TypeError('Release manifest must expose files and controls arrays.');
}

function normalizeRoutePattern(value) {
  if (typeof value !== 'string' || !value.startsWith('/') || value.includes('*') || value.includes('?') || value.includes('#')) {
    throw new TypeError(`Invalid release HTML route: ${JSON.stringify(value)}`);
  }
  return value;
}

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const paths = [];
  for (const entry of entries.toSorted((left, right) => compareText(left.name, right.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) paths.push(...await walk(path));
    else if (entry.isFile()) paths.push(path);
  }
  return paths;
}

function sha256(value) {
  return createHash('sha256').update(value).digest('hex');
}

function normalizePath(path) {
  return sep === '/' ? path : path.split(sep).join('/');
}

function compareText(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}
